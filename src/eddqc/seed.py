"""Reference table rows built from refdata.py.

Used two ways: written out as sql/06_seed_reference.sql for the database, and
turned straight into DataFrames so unit tests can run without SQL Server.
"""
from __future__ import annotations

from pathlib import Path

from . import refdata as R


def reference_tables() -> dict[str, tuple[list[str], list[tuple]]]:
    s = R.SITE
    t: dict[str, tuple[list[str], list[tuple]]] = {}
    t["ref_Site"] = (["site_code", "site_name", "county", "grid_crs"],
                     [(s["site_code"], s["site_name"], s["county"], s["grid_crs"])])
    t["ref_Location"] = (["location_code", "site_code", "location_type", "easting", "northing",
                          "ground_level_mod", "final_depth_m", "screen_top_m", "screen_base_m"],
                         [(l[0], s["site_code"], *l[1:]) for l in R.LOCATIONS])
    t["ref_Lab"] = (["lab_code", "lab_name", "accreditation"],
                    [(R.LAB["lab_code"], R.LAB["lab_name"], R.LAB["accreditation"])])
    t["ref_Analyte"] = (["cas_rn", "chemical_name", "analyte_group", "is_surrogate",
                         "common_lab_contaminant", "sum_into_cas"], list(R.ANALYTES))

    methods, ma, spikes = [], [], []
    for code, rules in R.METHOD_RULES.items():
        for matrix in R.MATRICES:
            ht, ext, tmin, tmax, ph, pres = rules[R.matrix_kind(matrix)]
            methods.append((code, matrix, R.METHOD_NAMES[code], R.METHOD_GROUP[code],
                            ht, ext, tmin, tmax, ph, pres))
    for (code, cas), lim in R.METHOD_ANALYTE_LIMITS.items():
        for matrix in R.MATRICES:
            k = R.matrix_kind(matrix)
            mdl, rl = lim[k]
            ma.append((code, matrix, cas, mdl, rl, R.UNITS[k]))
        if cas not in ("BTEX-TOT", "TPH-TOT-C10C40"):
            for qc_type, (lo, hi) in R.SPIKE_LIMITS.items():
                rpd = R.SPIKE_RPD_MAX[code] if qc_type == "MS" else None
                spikes.append((code, cas, qc_type, lo, hi, rpd))
    t["ref_Method"] = (["method_code", "matrix", "method_name", "analyte_group", "holding_time_days",
                        "extraction_holding_days", "temp_min_c", "temp_max_c", "ph_max", "preservation"],
                       methods)
    t["ref_Method_Analyte"] = (["method_code", "matrix", "cas_rn", "mdl", "rl", "unit"], ma)
    t["ref_Surrogate_Limit"] = (["method_code", "cas_rn", "lower_pct", "upper_pct"],
                                [(m, c, lo, hi) for m, lst in R.SURROGATES.items() for c, lo, hi in lst])
    t["ref_Spike_Limit"] = (["method_code", "cas_rn", "qc_type", "lower_pct", "upper_pct", "rpd_max"], spikes)

    crit = []
    for kind, values in R.SCREENING.items():
        matrix = "SO" if kind == "S" else "WG"
        for cas, val in values.items():
            crit.append((cas, matrix, R.SCREENING_NAME[kind], val, R.UNITS[kind],
                         "Illustrative value for a portfolio project, not for real assessment"))
    t["ref_Screening_Criterion"] = (["cas_rn", "matrix", "criterion_name", "criterion_value", "unit",
                                     "source_note"], crit)
    t["ref_Valid_Value"] = (["domain", "code", "description"],
                            [(d, c, desc) for d, codes in R.VALID_VALUES.items() for c, desc in codes.items()])
    t["qc_Rule"] = (["rule_id", "family", "rule_name", "severity", "default_qualifier", "description"],
                    list(R.RULES))
    return t


def _q(v) -> str:
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return repr(v)
    return "N'" + str(v).replace("'", "''") + "'"


def build_seed_sql() -> str:
    parts = ["/* 06 - Reference data. GENERATED by eddqc.seed from refdata.py; do not edit by hand. */",
             "SET NOCOUNT ON;"]
    for table, (cols, rows) in reference_tables().items():
        for i in range(0, len(rows), 500):
            chunk = rows[i:i + 500]
            values = ",\n".join("    (" + ", ".join(_q(v) for v in r) + ")" for r in chunk)
            parts.append(f"INSERT INTO dbo.{table} ({', '.join(cols)}) VALUES\n{values};")
    parts.append("GO")
    return "\n\n".join(parts) + "\n"


def write_seed_sql(path: Path) -> None:
    path.write_text(build_seed_sql(), encoding="utf-8")
